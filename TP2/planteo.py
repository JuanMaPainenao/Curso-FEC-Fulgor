def traspuesta(M):
     filas = len(M)
     cols  = len(M[0])

     T = []
     for i in range(cols):
          fila = []
          for i in range(filas):
               fila.append(0)
          T.append(fila)

     for i in range(filas):
          for j in range(cols):
               T[j][i] = M[i][j]

     return T

def mult_matrices(A, B):
     filas_A = len(A)
     cols_A  = len(A[0])
     cols_B  = len(B[0])

     C = []
     for i in range(filas_A):
          fila = []
          for i in range(cols_B):
               fila.append(0)
          C.append(fila)

     for i in range(filas_A):
          for j in range(cols_B):
               acum = 0
               for k in range(cols_A):
                    acum = acum + A[i][k] * B[k][j]
               C[i][j] = acum % 2
     return C

